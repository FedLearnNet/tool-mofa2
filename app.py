from __future__ import annotations

from pathlib import Path
from typing import Any

import mofax as mfx
import pandas as pd
from matplotlib import pyplot as plt
from pydantic.dataclasses import dataclass
from pyfedappwrap.learning.app_types import BaseSelfLearnedApp
from pyfedappwrap.learning.run_runfig import AppConfig, AppOutputConfig, AppInputConfig


@dataclass
class MofaExplorationConfig(AppConfig):
    n_top_features: int = 20
    export_weights: bool = True
    export_factors: bool = True
    export_top_features: bool = True


@dataclass
class MofaExplorationInput(AppInputConfig):
    pass


@dataclass
class MofaExplorationOutput(AppOutputConfig):
    factors: Any | None = None
    weights: Any | None = None
    top_features: Any | None = None
    report: Any | None = None
    weights_plot: Path | None = None


class MofaExplorationApp(
    BaseSelfLearnedApp[MofaExplorationConfig, MofaExplorationInput, MofaExplorationOutput]):

    def __init__(self):
        super().__init__()

    def run_algorithm(self, data: MofaExplorationInput) -> MofaExplorationOutput:
        model = mfx.mofa_model("data/models/pbmc10k.hdf5")
        output = MofaExplorationOutput()

        n_factors = int(model.get_factors().shape[1])
        selected_factors = list(range(n_factors))

        weights_df = None
        if self.config.export_weights:
            weights_df = model.get_weights(df=True)
            output.weights = weights_df

        if self.config.export_factors:
            factors_df = model.get_factors(df=True)
            output.factors = factors_df

        if self.config.export_top_features:
            output.top_features = self._build_top_features(model, weights_df, selected_factors)

        output.report = self._build_report(model, output, selected_factors)
        output.weights_plot = self._export_weights_heatmap_png(model)

        return output

    def _build_top_features(self, model, weights_df: pd.DataFrame | None,
                            selected_factors: list[int] | None) -> pd.DataFrame:
        if weights_df is None:
            weights_df = model.get_weights(df=True)

        factor_columns = list(weights_df.columns)
        if selected_factors is not None:
            selected_names = {
                f"Factor{f + 1}" if isinstance(f, int) else str(f)
                for f in selected_factors
            }
            factor_columns = [col for col in factor_columns if col in selected_names]

        rows: list[dict[str, Any]] = []
        for factor in factor_columns:
            series = weights_df[factor].dropna()
            ranked = series.reindex(series.abs().sort_values(ascending=False).index).head(
                self.config.n_top_features)
            for rank, (feature, weight) in enumerate(ranked.items(), start=1):
                rows.append(
                    {
                        "factor": factor,
                        "rank": rank,
                        "feature": feature,
                        "weight": float(weight),
                        "abs_weight": float(abs(weight)),
                        "direction": "positive" if weight >= 0 else "negative",
                    }
                )

        return pd.DataFrame(rows)

    def _build_report(
            self,
            model,
            output: MofaExplorationOutput,
            selected_factors: list[int] | None,
    ) -> str:
        model_shape = getattr(model, "shape", ("?", "?"))
        groups = ", ".join(getattr(model, "groups", [])) or "n/a"
        views = ", ".join(getattr(model, "views", [])) or "n/a"
        factors_text = ", ".join(map(str, selected_factors)) if selected_factors else "all"

        report_parts = [
            "<h1>MOFA/MOFA+ downstream exploration report</h1>",
            "<p>Generated by the PoSyMed MofaExploration app.</p>",
            "<h2>Model summary</h2>",
            f"<ul><li>Cells/Samples: {model_shape[0]}</li>",
            f"<li>Features: {model_shape[1]}</li>",
            f"<li>Groups: {groups}</li>",
            f"<li>Views: {views}</li>",
            f"<li>Selected factors: {factors_text}</li></ul>",
        ]

        if isinstance(output.top_features, pd.DataFrame) and not output.top_features.empty:
            report_parts.append("<h2>Top features by factor</h2>")
            report_parts.append(output.top_features.head(50).to_html(index=False))

        report_parts.append(
            "<p>This app focuses on structured exports for PoSyMed workflows. "
            "Notebook-style plotting functions such as plot_weights, plot_factors_scatter, and plot_r2 can be added later as dedicated visual outputs.</p>"
        )

        return "\n".join(report_parts)

    def _export_weights_heatmap_png(self, model) -> Path:
        output_dir = Path("data")
        file_name: str = "weights_heatmap.png"
        output_dir.mkdir(parents=True, exist_ok=True)

        mfx.plot_weights(model, n_features=10)
        out_path = output_dir / file_name

        plt.gcf().savefig(out_path, dpi=200, bbox_inches="tight")
        plt.close(plt.gcf())

        return out_path
